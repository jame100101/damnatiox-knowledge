export type LocaleMessageKey = keyof (typeof messages)['zh-CN']

function normalizeLocale(value: unknown): KnowledgeLocale {
  return knowledgeLocaleOptions.some((option) => option.value === value)
    ? (value as KnowledgeLocale)
    : 'zh-CN'
}

export function useLocale() {
  const cookie = useCookie<KnowledgeLocale>('kb-locale', {
    default: () => 'zh-CN',
    sameSite: 'lax',
  })
  const locale = useState<KnowledgeLocale>('kb-locale-state', () =>
    normalizeLocale(cookie.value),
  )

  function setLocale(value: KnowledgeLocale) {
    locale.value = normalizeLocale(value)
    cookie.value = locale.value
  }

  const dateLocale = computed(() => (locale.value === 'en' ? 'en-US' : locale.value))
  const currentOption = computed(
    () =>
      knowledgeLocaleOptions.find((option) => option.value === locale.value) ||
      knowledgeLocaleOptions[0]!,
  )
  const t = (key: LocaleMessageKey) =>
    messages[locale.value][key] || messages['zh-CN'][key]

  return {
    locale,
    dateLocale,
    localeOptions: knowledgeLocaleOptions,
    currentOption,
    setLocale,
    t,
  }
}
